import { NavLink, useLocation } from 'react-router-dom';

const tabs = [
  { label: 'Home', path: '/home', icon: HomeIcon },
  { label: 'Cards', path: '/cards', icon: CardIcon },
  { label: 'Decks', path: '/decks', icon: DeckIcon },
  { label: 'Games', path: '/games/setup', icon: GameIcon },
];

// Bottom navigation bar. Hidden on the game play screen to maximise board space.
export default function BottomNav() {
  const location = useLocation();
  const hideOnPaths = [/^\/games\/\d+\/play/];
  if (hideOnPaths.some((r) => r.test(location.pathname))) return null;

  return (
    <nav
      className="fixed bottom-0 left-0 right-0 bg-surface border-t border-border z-50"
      style={{ paddingBottom: 'var(--safe-bottom)' }}
    >
      <div className="flex justify-around items-center h-16 max-w-lg mx-auto">
        {tabs.map(({ label, path, icon: Icon }) => (
          <NavLink
            key={path}
            to={path}
            className={({ isActive }) =>
              `flex flex-col items-center justify-center flex-1 h-full gap-1 text-xs font-semibold transition-colors ${
                isActive ? 'text-accent' : 'text-textMuted'
              }`
            }
          >
            <Icon className="w-6 h-6" />
            <span>{label}</span>
          </NavLink>
        ))}
      </div>
    </nav>
  );
}

